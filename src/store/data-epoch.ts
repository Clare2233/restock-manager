/**
 * 数据世代号（epoch）：一个**只会递增的数字**。
 *
 * ## 它解决什么问题
 *
 * 页面各自缓存在内存里（`store/items.store` 等），并且靠「超过 30 秒才算过期」
 * 来决定要不要重新查库。这对日常写操作够用 —— 数据变了，写操作顺手刷一遍。
 *
 * 但**备份导入 / 清空数据**是「整个库被换掉」，走的路径不经过那些写操作。
 * 于是可能出现这样一幕：刚导入完，首页显示的还是半个月前的物品列表，
 * 而用户必须手动杀掉 App 才能看到新数据。那种时候谁都会以为导入失败了。
 *
 * ## 为什么是一个数字，而不是「版本号」或事件总线
 *
 * 数字的好处是**只能被比较**：谁在什么时候看的、看了几次都不重要，
 * 只要「我看过的 epoch」与「现在的 epoch」不一样，就说明数据变过了。
 * 事件总线则要求关心这件事的页面**此刻已经挂载**才能收到通知，
 * 而 check 的时机恰好是「页面重新获得焦点」——那正是它离开期间发生的事。
 *
 * ## 为什么不做订阅
 *
 * 需要它的地方只有一处：`use-items.ts` 的 `useRefreshOnFocus`，
 * 在页面获得焦点时**读一次**当前值并与上次记住的值比较。
 * 那是一次性的读取，不是持续订阅 —— 订阅会让每个挂着的页面
 * 在 epoch 变化时白白重渲染一次，而它们本来就要在聚焦时重查库。
 * 将来若真出现「需要立刻响应」的场景，再加 `subscribe` 也不迟。
 */

let epoch = 0;

/** 当前世代号。用处是与「你上次看到的那个值」比较 */
export function getDataEpoch(): number {
  return epoch;
}

/**
 * 数据被整体替换之后调用（备份导入、清空数据）。
 *
 * **只由 `services/backup/import.ts` 调用**：数据被替换这件事只有那里知道，
 * 让别的模块各自 bump 的话，这个信号很快就不值钱了。
 */
export function bumpDataEpoch(): void {
  epoch += 1;
}

/** 仅测试用：把世代号归零，避免用例之间互相干扰 */
export function __resetDataEpoch(): void {
  epoch = 0;
}
